function zlStats=calcImpedanceLengthStatistics600A(dataSet,settings,...
                                                    verbose)

%
% Summary statistics
%

nS=size(dataSet.individual,1);
nL=size(dataSet.individual,2);
nE=size(dataSet.individual,3);

varsLeft =settings.pairwiseComparison(:,1);
varsRight =settings.pairwiseComparison(:,2);
nC=length(varsLeft);


% 'diffMedian',zeros(nC,nL).*nan,...
% 'diffMedianNorm',zeros(nC,nL).*nan,...

statsSLE_diff(nS,nL,nE) = ...
  struct('diffMedian',zeros(nC,1).*nan,...
         'diffMedianNorm',zeros(nC,1),...   
         'skewness',zeros(nC,2),...
         'vars',[]);

statsSL_diff(nS,nL) = ...
  struct('diffMedian',zeros(nC,1).*nan,...
         'diffMedianNorm',zeros(nC,1),...   
         'skewness',zeros(nC,2),...
         'vars',[]);

statsSE(nS,nE) = ...
  struct('corr_rho',zeros(nC,1).*nan,...
         'corr_pval',zeros(nC,1).*nan,...
         'corr_n',zeros(nC,1).*nan,...
         'skewness',zeros(nC,2).*nan,...
         'corrMedian_rho',zeros(nC,1).*nan,...
         'corrMedian_pval',zeros(nC,1).*nan,...
         'corrMedian_n',zeros(nC,1).*nan,...   
         'skewnessMedian',zeros(nC,2).*nan,...
         'vars',[]);
 
statsS(nS) = ...
  struct('corr_rho',zeros(nC,1).*nan,...
         'corr_pval',zeros(nC,1).*nan,...
         'corr_n',zeros(nC,1).*nan,...
         'skewness',zeros(nC,2),...
         'corrMedian_rho',zeros(nC,1).*nan,...
         'corrMedian_pval',zeros(nC,1).*nan,...
         'corrMedian_n',zeros(nC,1).*nan,...
         'skewnessMedian',zeros(nC,2),...
         'vars',[]);

%%
% Individual statistics
%%
for idS=1:1:nS
  for idE=1:1:nE
    for idC=1:1:nC    
      statsSE(idS,idE).vars=...
        [statsSE(idS,idE).vars,...
        {[varsLeft{idC},'_',varsRight{idC}]}];   
    end
    for idL=1:1:nL
      for idC=1:1:nC
        statsSLE_diff(idS,idL,idE).vars=...
          [statsSLE_diff(idS,idL,idE).vars,...
          {[varsLeft{idC},'_',varsRight{idC}]}];
        
      end
    end
  end
end
fprintf('\ncalcImpedanceLengthStatistics600A\n');
fprintf('\tsegment x experiment\n');
for idS=1:1:nS
  for idE=1:1:nE
    for idC=1:1:nC 

      medianSet1 = [];
      medianSet2 = [];
      dataSet1   = [];
      dataSet2   = [];

      for idL=1:1:nL
        
        idT=dataSet.T.idS==idS ...
          & dataSet.T.idL==idL ...
          & dataSet.T.idE==idE ...
          & ~isnan(dataSet.T.(varsLeft{idC}));            
        y1 = dataSet.T.(varsLeft{idC})(idT);

        idT=dataSet.T.idS==idS ...
          & dataSet.T.idL==idL ...
          & dataSet.T.idE==idE ...
          & ~isnan(dataSet.T.(varsRight{idC}));           
        y2 = dataSet.T.(varsRight{idC})(idT);            
      
        

        if(~isempty(y1) && ~isempty(y2))

          assert(length(y1)==length(y2));
          m1=median(y1);
          m2=median(y2);
  
          medianSet1=[medianSet1;m1];
          medianSet2=[medianSet2;m2];
  
          dataSet1=[dataSet1;y1];
          dataSet2=[dataSet2;y2];
  
          statsSLE_diff(idS,idL,idE).diffMedian(idC,1)=m1-m2;
          
          ss=getSummaryStatistics(y1);
          assert(abs(ss.x(5)-0.75)<1e-6 && abs(ss.x(3)-0.25)<1e-6);
          
          %w = ss.y(5)-ss.y(3);        
          w = mad(y1,1);
          statsSLE_diff(idS,idL,idE).diffMedianNorm(idC,1)=(m1-m2)/w; 

          statsSLE_diff(idS,idL,idE).skewness(idC,1)=skewness(y1);
          statsSLE_diff(idS,idL,idE).skewness(idC,2)=skewness(y2);
  
        else
          statsSLE_diff(idS,idL,idE).diffMedian(idC,1)=nan;
          statsSLE_diff(idS,idL,idE).diffMedianNorm(idC,1)=nan;
          statsSLE_diff(idS,idL,idE).skewness(idC,1)=nan;
          statsSLE_diff(idS,idL,idE).skewness(idC,2)=nan;
          fprintf('\t%i,%i,%i - %i\n',idS,idE,idL, idC);
          fprintf('\t*%i - too little data\n',length(y1));
        end
      end 
      if(~isempty(medianSet1))
        [rhoM,pvalM] = corr(medianSet1,medianSet2,'Type','Spearman');
        statsSE(idS,idE).corrMedian_n(idC)    = length(medianSet1);       
        statsSE(idS,idE).corrMedian_rho(idC)  = rhoM;   
        statsSE(idS,idE).corrMedian_pval(idC) = pvalM;  
        statsSE(idS,idE).skewnessMedian(idC,1) = skewness(medianSet1);
        statsSE(idS,idE).skewnessMedian(idC,2) = skewness(medianSet2);
        [rho,pval] = corr(dataSet1,dataSet2,'Type','Spearman');
        statsSE(idS,idE).corr_n(idC)    = length(dataSet1);       
        statsSE(idS,idE).corr_rho(idC)  = rho;   
        statsSE(idS,idE).corr_pval(idC) = pval;  
        statsSE(idS,idE).vars(idC)=...
          {[varsLeft{idC},'_',varsRight{idC}]};
        statsSE(idS,idE).skewness(idC,1) = skewness(dataSet1);
        statsSE(idS,idE).skewness(idC,2) = skewness(dataSet2);
      end

    end    
  end
end

%
% Group statistics
%
for idS=1:1:nS

  for idC=1:1:nC
    statsS(idS).vars= ...
      [statsS(idS).vars,...
       {[varsLeft{idC},'_',varsRight{idC}]}]; 
  end
  for idL=1:1:nL
    for idC=1:1:nC
      statsSL_diff(idS,idL).vars=...
        [statsSL_diff(idS,idL).vars,...
         {[varsLeft{idC},'_',varsRight{idC}]}];  
    end
  end

end
fprintf('\tsegment\n');
for idS=1:1:nS
  for idC=1:1:nC 

    medianSet1 = [];
    medianSet2 = [];
    dataSet1   = [];
    dataSet2   = [];

    for idL=1:1:nL

      idT=dataSet.T.idS==idS ...
        & dataSet.T.idL==idL ...
        & ~isnan(dataSet.T.(varsLeft{idC}));            
      y1 = dataSet.T.(varsLeft{idC})(idT);

      idT=dataSet.T.idS==idS ...
        & dataSet.T.idL==idL ...
        & ~isnan(dataSet.T.(varsRight{idC}));           
      y2 = dataSet.T.(varsRight{idC})(idT);            

      if(~isempty(y1) && ~isempty(y2))
        assert(length(y1)==length(y2));  
  
        m1=median(y1);
        m2=median(y2);
  
        medianSet1=[medianSet1;median(y1)];
        medianSet2=[medianSet2;median(y2)];
  
        dataSet1=[dataSet1;y1];
        dataSet2=[dataSet2;y2];
  
        statsSL_diff(idS,idL).diffMedian(idC,1)=m1-m2;
  
        ss=getSummaryStatistics(y1);
        assert(abs(ss.x(5)-0.75)<1e-6 && abs(ss.x(3)-0.25)<1e-6);
        
        %w = (ss.y(5)-ss.y(3)) ;        
        w = mad(y1,1);
        statsSL_diff(idS,idL).diffMedianNorm(idC,1)=(m1-m2)/w;  

        statsSL_diff(idS,idL).skewness(idC,1)=skewness(y1);
        statsSL_diff(idS,idL).skewness(idC,2)=skewness(y2);        
      else
        statsSL_diff(idS,idL).diffMedian(idC,1)=nan;
        statsSL_diff(idS,idL).diffMedianNorm(idC,1)=nan;
        statsSL_diff(idS,idL).skewness(idC,1)=nan;
        statsSL_diff(idS,idL).skewness(idC,2)=nan; 
        fprintf('\t%i,%i - %i\n',idS,idL, idC);
        fprintf('\t*%i - too little data\n',length(y1));        
      end


    end 
    [rhoM,pvalM] = corr(medianSet1,medianSet2,'Type','Spearman');
    statsS(idS).corrMedian_n(idC)    = length(medianSet1);       
    statsS(idS).corrMedian_rho(idC)  = rhoM;   
    statsS(idS).corrMedian_pval(idC) = pvalM;  
    statsS(idS).skewnessMedian(idC,1)=skewness(medianSet1);
    statsS(idS).skewnessMedian(idC,2)=skewness(medianSet2);

    [rho,pval] = corr(dataSet1,dataSet2,'Type','Spearman');
    statsS(idS).corr_n(idC)    = length(dataSet1);       
    statsS(idS).corr_rho(idC)  = rho;   
    statsS(idS).corr_pval(idC) = pval;     
    statsS(idS).skewness(idC,1) = skewness(dataSet1);
    statsS(idS).skewness(idC,2) = skewness(dataSet2);
    
  end    
end

zlStats.corrS   = statsS;
zlStats.corrSE  = statsSE;
zlStats.diffSLE = statsSLE_diff;
zlStats.diffSL  = statsSL_diff;

if(verbose==1)

  fprintf('\n\nSkewness: corrS\n');
  fprintf('idS\tsk11\tsk12\tsk21\tsk22\n');
  corrSSummary=[];
  for idS=1:1:nS
    fprintf('%i\t%1.2f\t%1.2f\t%1.2f\t%1.2f\n',idS,...
        statsS(idS).skewness(1,1),...
        statsS(idS).skewness(1,2),...
        statsS(idS).skewness(2,1),...
        statsS(idS).skewness(2,2));
    corrSSummary = [corrSSummary;...
                  statsS(idS).skewness(1,1),...
                  statsS(idS).skewness(1,2),...
                  statsS(idS).skewness(2,1),...
                  statsS(idS).skewness(2,2)];
  end
  
  fprintf('\nmin\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    min(corrSSummary(:,1)),...
    min(corrSSummary(:,2)), ...
    min(corrSSummary(:,3)), ...
    min(corrSSummary(:,4)));

  fprintf('\nmax\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    max(corrSSummary(:,1)),...
    max(corrSSummary(:,2)), ...
    max(corrSSummary(:,3)), ...
    max(corrSSummary(:,4)));

  fprintf('\nmed\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    median(corrSSummary(:,1)),...
    median(corrSSummary(:,2)), ...
    median(corrSSummary(:,3)), ...
    median(corrSSummary(:,4)));



  fprintf('\n\nSkewness: diffSL\n');
  fprintf('idS\tsk11\tsk12\tsk21\tsk22\n');
  diffSLSummary=[];
  for idS=1:1:nS
    for idL=1:1:nL
      fprintf('%i\t%1.2f\t%1.2f\t%1.2f\t%1.2f\n',idS,...
          statsSL_diff(idS,idL).skewness(1,1),...
          statsSL_diff(idS,idL).skewness(1,2),...
          statsSL_diff(idS,idL).skewness(2,1),...
          statsSL_diff(idS,idL).skewness(2,2));

      diffSLSummary = [diffSLSummary;...
              statsSL_diff(idS,idL).skewness(1,1),...
              statsSL_diff(idS,idL).skewness(1,2),...
              statsSL_diff(idS,idL).skewness(2,1),...
              statsSL_diff(idS,idL).skewness(2,2)];
    end
  end

  fprintf('\nmin\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    min(diffSLSummary(:,1)),...
    min(diffSLSummary(:,2)), ...
    min(diffSLSummary(:,3)), ...
    min(diffSLSummary(:,4)));

  fprintf('\nmax\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    max(diffSLSummary(:,1)),...
    max(diffSLSummary(:,2)), ...
    max(diffSLSummary(:,3)), ...
    max(diffSLSummary(:,4)));

  fprintf('\nmed\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    median(diffSLSummary(:,1)),...
    median(diffSLSummary(:,2)), ...
    median(diffSLSummary(:,3)), ...
    median(diffSLSummary(:,4)));


  fprintf('\n\nSkewness: corrSE\n');
  fprintf('idS\tidE\tsk11\tsk12\tsk21\tsk22\n');
  corrSESummary=[];
  for idS=1:1:nS
    for idE=1:1:nE
      fprintf('%i\t%i\t%1.2f\t%1.2f\t%1.2f\t%1.2f\n',idS,idE,...
          statsSE(idS,idE).skewness(1,1),...
          statsSE(idS,idE).skewness(1,2),...
          statsSE(idS,idE).skewness(2,1),...
          statsSE(idS,idE).skewness(2,2));
      corrSESummary = [corrSESummary;...
                        statsSE(idS,idE).skewness(1,1),...
                        statsSE(idS,idE).skewness(1,2),...
                        statsSE(idS,idE).skewness(2,1),...
                        statsSE(idS,idE).skewness(2,2)];
    end
  end

  fprintf('\nmin\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    min(corrSESummary(:,1)),...
    min(corrSESummary(:,2)), ...
    min(corrSESummary(:,3)), ...
    min(corrSESummary(:,4)));

  fprintf('\nmax\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    max(corrSESummary(:,1)),...
    max(corrSESummary(:,2)), ...
    max(corrSESummary(:,3)), ...
    max(corrSESummary(:,4)));

  fprintf('\nmed\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    median(corrSESummary(:,1)),...
    median(corrSESummary(:,2)), ...
    median(corrSESummary(:,3)), ...
    median(corrSESummary(:,4)));  

  fprintf('\n\nSkewness: diffSLE\n');
  fprintf('idS\tidE\tsk11\tsk12\tsk21\tsk22\n');
  diffSLESummary=[];
  for idS=1:1:nS
    for idL=1:1:nL
      for idE=1:1:nE
        fprintf('%i\t%i\t%i\t%1.2f\t%1.2f\t%1.2f\t%1.2f\n',idS,idL,idE,...
            statsSLE_diff(idS,idL,idE).skewness(1,1),...
            statsSLE_diff(idS,idL,idE).skewness(1,2),...
            statsSLE_diff(idS,idL,idE).skewness(2,1),...
            statsSLE_diff(idS,idL,idE).skewness(2,2));

        diffSLESummary = [diffSLESummary;...
                        statsSLE_diff(idS,idL,idE).skewness(1,1),...
                        statsSLE_diff(idS,idL,idE).skewness(1,2),...
                        statsSLE_diff(idS,idL,idE).skewness(2,1),...
                        statsSLE_diff(idS,idL,idE).skewness(2,2)];
      end
    end
  end


  fprintf('\nmin\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    min(diffSLESummary(:,1)),...
    min(diffSLESummary(:,2)), ...
    min(diffSLESummary(:,3)), ...
    min(diffSLESummary(:,4)));

  fprintf('\nmax\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    max(diffSLESummary(:,1)),...
    max(diffSLESummary(:,2)), ...
    max(diffSLESummary(:,3)), ...
    max(diffSLESummary(:,4)));

  fprintf('\nmed\t%1.2f\t%1.2f\t%1.2f\t%1.2f',...
    median(diffSLESummary(:,1)),...
    median(diffSLESummary(:,2)), ...
    median(diffSLESummary(:,3)), ...
    median(diffSLESummary(:,4)));  

  here=1;
  
end