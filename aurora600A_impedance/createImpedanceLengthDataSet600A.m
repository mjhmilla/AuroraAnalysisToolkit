function dataSet = createImpedanceLengthDataSet600A(...
                        experimentList,...
                        segmentSeries,...
                        categories,...
                        keyWords,...
                        numberOfTableRows,...
                        projectFolders,...
                        settings)



tableColumnNames={'idE','idS','idL',...
                  'f','s','l',...
                  'fa','sa','la',...
                  'fp','sp','lp'};

tableColumnType={'int8','int8','int8',...
                  'double','double','double',...
                  'double','double','double',...
                  'double','double','double'};

tableColumnUnits={'','','',...
                  'Hz','mN/mm','mN/mm',...
                  'Hz','mN/mm','mN/mm',...
                  'Hz','mN/mm','mN/mm'};

tableColumnDescription = ...
  {'exp. index', 'seg. index', 'length index',...
  'frequency vector that goes with (s,l) or (storage, loss)',...
  'storage vector from an active fiber trial',...
  'loss vector from an active fiber trial',...
  'frequency vector that goes with (sA, lA) or (storageActive, lossActive)',...
  'storage vector from an active fiber trial with the passive component removed',...
  'loss vector from an active fiber trial with the passive component removed',...  
  'frequency vector from a passive fiber trial that goes with (sP,lP) or (storagePassive,lossPassive)',...
  'storage vector from a passive fiber trial',...
  'loss vector from a passive fiber trial'};

tableDescription=...
  ['This table contains the frequency dependent storage and loss ',...
  'vectors that best fits the total, active, and passive response',...
  'of a fiber when exposed to a mechanical vibration'];

dataSet(length(segmentSeries),...
        length(categories.length.value),...
        length(experimentList)) = ...
        struct('lengthAtLo',nan,...
               'forceAtLo',nan,...               
               'lengthNominalMM',nan,...
               'amplitudeMM',nan,...
               'bandwidthHz',nan,...
               'T',[],...
               'columnTypes',[],...
               'columnNames',[]);

%Pre allocate all of the tables
for idxE=1:1:length(experimentList)
  for idxL=1:1:length(categories.length.value)
    for idxS=1:1:length(segmentSeries)
      dataSet(idxS,idxL,idxE) = ...
              struct('lengthAtLo',nan,...
                     'forceAtLo',nan,...               
                     'lengthNominalMM',nan,...
                     'amplitudeMM',nan,...
                     'bandwidthHz',nan,...
                     'T',[],...
                     'columnTypes',[],...
                     'columnNames',[]);

      dataSet(idxS,idxL,idxE).T=table('Size',[numberOfTableRows,length(tableColumnNames)],...
                      'VariableNames',tableColumnNames,...
                      'VariableTypes',tableColumnType);

      dataSet(idxS,idxL,idxE).T.Properties.VariableUnits=tableColumnUnits;
      dataSet(idxS,idxL,idxE).T.Properties.VariableDescriptions=tableColumnDescription;
      dataSet(idxS,idxL,idxE).T.Properties.Description=tableDescription;
      dataSet(idxS,idxL,idxE).columnTypes=tableColumnType;
      dataSet(idxS,idxL,idxE).columnNames=tableColumnNames;
      for idxC=1:1:length(tableColumnType)
        switch tableColumnType{idxC}
          case 'int8'
            switch tableColumnNames{idxC}
              case 'idE'
                dataSet(idxS,idxL,idxE).T.(tableColumnNames{idxC})(:)=idxE;
              case 'idS'
                dataSet(idxS,idxL,idxE).T.(tableColumnNames{idxC})(:)=idxS;
              case 'idL'
                dataSet(idxS,idxL,idxE).T.(tableColumnNames{idxC})(:)=idxL;
              otherwise
                assert(0,'Error: unrecognized id');
            end
          case 'double'
            dataSet(idxS,idxL,idxE).T.(tableColumnNames{idxC})(:)=nan;
          otherwise
            assert(0,'Error: Unrecognized type');
        end
        
      end
    end
  end
end

for idxE=1:1:length(experimentList)
  trialList = dir(fullfile(projectFolders.output600A_json,...
                    experimentList{idxE}));

  for idxTrial=1:1:length(trialList)
    if(contains(trialList(idxTrial).name,'.json'))

      %Go get the active trial, and then its passive pair
      if(contains(trialList(idxTrial).name,...
         keyWords.active))

        %Make sure that this active file has a unique length id
        idxL = nan;
        for i = 1:1:length(categories.length.str)
          if(contains(trialList(idxTrialA).name,categories.length.str{i}))
            assert(isnan(idxL),'Error: there appear to be two valid active trials');
            idxL=i;
          end
        end
        assert(~isnan(idxL),'Error: could not find a valid length category');



        

      end
    end
  end

end

